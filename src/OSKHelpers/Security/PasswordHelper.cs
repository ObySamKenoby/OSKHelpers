namespace OSKHelpers.Security
{
    /// <summary>
    /// Provides utilities for secure password hashing and verification<br/>
    /// using PBKDF2 with SHA-256 and a random per-user salt (see <see cref="PasswordHash"/>).
    /// </summary>
    /// <remarks>
    /// Hashes created by previous versions (PBKDF2 with SHA-1, 36 bytes) are still verified;<br/>
    /// <see cref="RequiresRehash(byte[])"/> identifies them so that they can be regenerated.
    /// </remarks>
    public static class PasswordHelper
    {
        #region Methods

        /// <summary>
        /// Hashes a plain-text password using PBKDF2 with a randomly generated salt.
        /// </summary>
        /// <param name="password">The plain-text password to hash.</param>
        /// <returns>
        /// A byte array containing format version, salt and hash (see <see cref="PasswordHash.ToArray"/>),
        /// to be stored to allow future verification.
        /// </returns>
        /// <example>
        /// <code>
        /// user.PasswordHash = PasswordHelper.HashPassword("myPassword");
        /// </code>
        /// </example>
        public static byte[] HashPassword(string password)
        {
            var hash = new PasswordHash(password);
            return hash.ToArray();
        }

        /// <summary>
        /// Verifies a plain-text password against a stored hash.<br/>
        /// Uses a constant-time comparison to prevent timing attacks.
        /// </summary>
        /// <param name="password">The plain-text password to verify.</param>
        /// <param name="hash">The stored password hash, generated by <see cref="HashPassword(string)"/>.</param>
        /// <returns>
        /// <c>true</c> if the password matches the stored hash; otherwise <c>false</c>.
        /// </returns>
        public static bool VerifyPassword(string password, byte[] hash)
        {
            var challenge = new PasswordHash(hash);
            return challenge.Verify(password);
        }

        /// <summary>
        /// Returns true if the stored hash uses a format older than the current one;<br/>
        /// after a successful <see cref="VerifyPassword(string, byte[])"/> the password should be hashed again with
        /// <see cref="HashPassword(string)"/> and the stored value replaced.
        /// </summary>
        /// <param name="hash">The stored password hash.</param>
        /// <returns><c>true</c> if the hash should be regenerated.</returns>
        public static bool RequiresRehash(byte[] hash)
        {
            var stored = new PasswordHash(hash);
            return stored.RequiresRehash;
        }

        #endregion
    }
}
